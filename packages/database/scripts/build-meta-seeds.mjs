function readJson(fileName) {
  const filePath = path.join(jsonDir, fileName);
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function readOptionalJson(filePath, fallback = []) {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function sqlValue(value) {
  if (value === undefined || value === null || value === "") return "NULL";
  if (typeof value === "number")
    return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (typeof value === "object") return quote(JSON.stringify(value));
  return quote(String(value));
}

function quote(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function pickWikiDataId(row) {
  return row.wikiDataId ?? row.wiki_data_id ?? null;
}

function normalizeAdminLevel(row, fallbackLevel) {
  return row.level ?? fallbackLevel;
}

function isSettlement(row) {
  return row.type === undefined || row.type === null
    ? Boolean(row.latitude && row.longitude)
    : !adminOnlyLocalityTypes.has(row.type);
}

function writeSeed(fileName, tableName, columns, rows) {
  const filePath = path.join(outDir, fileName);
  const lines = [
    "-- Generated by packages/database/scripts/build-meta-seeds.mjs",
    `-- Source: ${sourceDir}`,
    `-- Rows: ${rows.length}`,
    "",
    `TRUNCATE TABLE ${tableName} RESTART IDENTITY CASCADE;`,
    "",
  ];

  for (let i = 0; i < rows.length; i += batchSize) {
    const batch = rows.slice(i, i + batchSize);
    lines.push(
      `INSERT INTO ${tableName} (${columns.join(", ")}) VALUES`,
      batch
        .map(
          (row) =>
            `  (${columns.map((column) => sqlValue(row[column])).join(", ")})`,
        )
        .join(",\n") + ";",
      "",
    );
  }

  fs.writeFileSync(filePath, lines.join("\n"));
  return { filePath, rows: rows.length };
}

function buildRegions() {
  return readJson("regions.json").map((region) => ({
    id: region.id,
    name: region.name,
    translations: region.translations,
    created_at: null,
    updated_at: defaultTimestamp,
    flag: 1,
    wiki_data_id: pickWikiDataId(region),
  }));
}

