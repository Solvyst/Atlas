function buildCurrencies(countries) {
  const byCode = new Map();

  for (const country of countries) {
    if (!country.currency) continue;
    if (!byCode.has(country.currency)) {
      byCode.set(country.currency, {
        code: country.currency,
        name: country.currency_name,
        symbol: country.currency_symbol,
      });
    }
  }

  return [...byCode.values()].sort((a, b) => a.code.localeCompare(b.code));
}

function buildTimezones(countries) {
  const timezones = [];
  let id = 1;

  for (const country of countries) {
    for (const timezone of country.timezones ?? []) {
      timezones.push({
        id: id++,
        country_id: country.id,
        zone_name: timezone.zoneName,
        gmt_offset: timezone.gmtOffset,
        gmt_offset_name: timezone.gmtOffsetName,
        abbreviation: timezone.abbreviation,
        tz_name: timezone.tzName,
      });
    }
  }

  return timezones;
}

